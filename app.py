from __future__ import annotations

import pandas as pd
import streamlit as st
from botocore.exceptions import BotoCoreError, ClientError, ProfileNotFound

from cloudsec_scanner.aws_session import create_aws_session
from cloudsec_scanner.reports import csv_bytes, json_bytes
from cloudsec_scanner.scanner import CloudSecurityScanner


st.set_page_config(page_title="AWS Cloud Security Scanner", page_icon="🛡️", layout="wide")
st.title("🛡️ AWS Cloud Security Scanner")
st.caption("Read-only AWS configuration assessment · S3 · IAM · VPC · EBS · RDS · CloudTrail")

with st.sidebar:
    st.header("Scan configuration")
    profile = st.text_input("AWS CLI profile", value="cloudsec-readonly", help="Leave blank to use the default AWS credential chain.")
    regions_text = st.text_input("AWS regions (comma-separated)", value="us-east-1")
    st.info("The scanner only calls AWS read/list/describe APIs. It does not create, modify, or delete AWS resources.")
    run_scan = st.button("Run security scan", type="primary", use_container_width=True)

st.markdown("### What this scanner checks")
coverage = [
    "S3 public access controls, bucket policy status, public ACL grants, explicit encryption configuration, versioning and access logging",
    "Root account MFA and root access-key presence; obvious wildcard and service-wide IAM policy permissions",
    "Security groups with inbound rules open to 0.0.0.0/0 or ::/0",
    "Unencrypted EBS volumes and publicly accessible or unencrypted RDS instances",
    "Multi-region CloudTrail coverage, logging status and log-file validation",
]
for item in coverage:
    st.markdown(f"- {item}")

if run_scan:
    regions = [region.strip() for region in regions_text.split(",") if region.strip()]
    if not regions:
        st.error("Enter at least one AWS region, for example us-east-1.")
    else:
        try:
            with st.spinner("Connecting to AWS and reviewing configuration metadata…"):
                session = create_aws_session(profile, regions[0])
                report = CloudSecurityScanner(session).scan(regions)
            st.session_state["scan_report"] = report
        except ProfileNotFound as exc:
            st.error(f"AWS profile not found: {exc}. Check `aws configure list-profiles`.")
        except (ClientError, BotoCoreError) as exc:
            st.error(f"AWS connection or scan error: {exc}")
        except Exception as exc:
            st.error(f"Unexpected scan error: {exc}")

report = st.session_state.get("scan_report")
if report:
    st.divider()
    st.subheader("Scan results")
    st.write(f"**AWS account:** `{report.account_id}`  ·  **Identity:** `{report.caller_arn}`")
    st.write(f"**Scanned regions:** {', '.join(report.regions)}  ·  **Time (UTC):** {report.scanned_at}")

    summary = report.summary()
    cols = st.columns(5)
    for col, severity in zip(cols, ["CRITICAL", "HIGH", "MEDIUM", "LOW", "INFO"]):
        col.metric(severity, summary.get(severity, 0))
    st.metric("Total findings", summary.get("TOTAL", 0))

    if report.findings:
        table = pd.DataFrame([finding.to_dict() for finding in report.findings])
        display_columns = ["severity", "service", "title", "resource_id", "region", "finding_id"]
        st.dataframe(table[display_columns], use_container_width=True, hide_index=True)
        selected = st.selectbox(
            "Inspect finding",
            options=list(range(len(report.findings))),
            format_func=lambda index: f"[{report.findings[index].severity}] {report.findings[index].title} — {report.findings[index].resource_id}",
        )
        finding = report.findings[selected]
        st.markdown(f"#### {finding.title}")
        st.write(f"**Severity:** {finding.severity} · **Service:** {finding.service} · **Region:** {finding.region}")
        st.write(finding.description)
        st.markdown("**Evidence**")
        st.json(finding.evidence)
        st.markdown("**Recommended remediation**")
        st.write(finding.remediation)
        if finding.compliance_tags:
            st.caption("Reference tags: " + ", ".join(finding.compliance_tags))
    else:
        st.success("No findings were generated by the enabled checks. Review diagnostics and scope before treating this as a clean bill of health.")

    if report.diagnostics:
        with st.expander(f"Checks skipped or incomplete ({len(report.diagnostics)})"):
            for diagnostic in report.diagnostics:
                st.warning(diagnostic)

    st.download_button("Download JSON report", data=json_bytes(report), file_name=f"aws-security-scan-{report.account_id}.json", mime="application/json")
    st.download_button("Download CSV report", data=csv_bytes(report), file_name=f"aws-security-scan-{report.account_id}.csv", mime="text/csv")
else:
    st.info("Configure an AWS read-only profile in the sidebar, then click **Run security scan**.")

st.divider()
st.caption("Important: Findings are configuration signals, not proof of exploitability. Validate each result in context. This tool does not scan object contents, inspect guest OS vulnerabilities, or execute remediation actions.")
